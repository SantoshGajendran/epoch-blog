import { z } from "zod";

export const siteConfigSchema = z.object({
  name: z.string().min(1),
  tagline: z.string().min(1),
  description: z.string().min(1),
  url: z.string().url(),
  author: z.object({
    name: z.string().min(1),
    bio: z.string().min(1),
    avatar: z.string().optional(),
    twitter: z.string().optional(),
    github: z.string().optional(),
  }),
  ui: z.object({
    searchPlaceholder: z.string(),
    searchButtonLabel: z.string(),
    searchAriaLabel: z.string(),
    themeToggleAriaLabel: z.string(),
    allTopicsLabel: z.string(),
    mapViewLabel: z.string(),
    listViewLabel: z.string(),
    prototypeHint: z.string(),
    readPostLabel: z.string(),
    minReadSuffix: z.string(),
    noSearchResultsLabel: z.string(),
    themeLightLabel: z.string().default("Light"),
    themeDarkLabel: z.string().default("Dark"),
    searchShortcutLabel: z.string().default("Ctrl K"),
    keyTakeawaysTitle: z.string().default("Key takeaways"),
    tableOfContentsTitle: z.string().default("On this page"),
    seriesPartPrefix: z.string().default("Part"),
    seriesOfPrefix: z.string().default("of"),
    previousPostLabel: z.string().default("Previous"),
    nextPostLabel: z.string().default("Next"),
    relatedPostsTitle: z.string().default("Related explorations"),
    sharePostLabel: z.string().default("Share"),
    linkCopiedLabel: z.string().default("Link copied"),
    backToMapLabel: z.string().default("Back to map"),
    actionSwitchThemeLabel: z.string().default("Toggle theme"),
    actionShowMapLabel: z.string().default("Switch to map view"),
    actionShowListLabel: z.string().default("Switch to list view"),
    searchGroupPostsLabel: z.string().default("Posts"),
    searchGroupTopicsLabel: z.string().default("Topics"),
    searchGroupSeriesLabel: z.string().default("Series"),
    searchGroupActionsLabel: z.string().default("Actions"),
  }),
});

export type SiteConfig = z.infer<typeof siteConfigSchema>;
